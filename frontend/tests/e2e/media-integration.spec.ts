import { selectOption } from './ui-controls'
import {test,expect} from '@playwright/test'
import {resolve} from 'node:path'
test('media choices, explicit plan confirmation, supplement and connection drawer',async({page},info)=>{
  const errors:string[]=[], writes:{body:unknown,key:string|undefined}[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.route('**/api/v1/**',async route=>{
    const req=route.request(),path=new URL(req.url()).pathname
    if(path.endsWith('/content')) return route.fulfill({status:200,contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><rect width="80" height="80" fill="#f2dfcf"/></svg>'})
    if(path.includes('/tasks/') && path.includes('/video/')) {writes.push({body:req.postDataJSON(),key:req.headers()['idempotency-key']});return route.fulfill({json:{kind:'video',status:'generating'}})}
    if(path.endsWith('/connection')) return route.fulfill({json:{id:null,kind:path.includes('/image/')?'image':'video',base_url:null,revision:0,has_service_key:false,has_management_key:false,default_config_id:null,image_model:null}})
    return route.fulfill({json:[]})
  })
  await page.goto('/tests/fixtures/media-integration.html')
  await expect(page.getByRole('combobox',{name:'目标平台',exact:true})).toHaveValue('')
  await selectOption(page.getByRole('combobox',{name:'目标平台',exact:true}), 'pinduoduo')
  await selectOption(page.getByRole('combobox',{name:'图片用途',exact:true}), 'pdd_white_background')
  await selectOption(page.getByRole('combobox',{name:'目标平台',exact:true}), 'taobao')
  await expect(page.locator('.media-choices select[data-select-id$="-output"]')).toHaveValue('pdd_white_background')
  await expect(page.locator('.media-choices .el-select__selected-item').filter({hasText:'白底图'})).toBeVisible()
  await selectOption(page.getByRole('combobox',{name:'图片用途',exact:true}), 'long_image')
  await expect(page.locator('.media-choices select[data-select-id$="-output"]')).toHaveValue('long_image')
  await expect(page.locator('.media-choices .el-select__selected-item').filter({hasText:'商品长图'})).toBeVisible()
  await page.screenshot({path:resolve('../docs/verification/screenshots/image-outputs-2026-10-18-'+info.project.name+'.png'),fullPage:true})
  await selectOption(page.getByRole('combobox',{name:'图片用途',exact:true}), 'main_image')
  await expect(page.locator('input[type=radio]:checked')).toHaveCount(0)
  await page.locator('.frame-option').click()
  await expect(page.getByRole('radio')).toBeChecked()
  expect(writes).toHaveLength(0)
  await page.locator('[data-view-plan]').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByText('展示真实商品外观',{exact:true})).toBeVisible()
  await page.screenshot({path:resolve('../docs/verification/screenshots/element-plus-2026-10-16-media-plan-'+info.project.name+'.png'),fullPage:true})
  await page.locator('[data-confirm-plan]').click()
  await expect(page.getByText(/本次确认不会再次收费/)).toBeVisible()
  expect(writes).toHaveLength(0)
  await page.locator('[data-send-confirmation]').click()
  await expect.poll(()=>writes.length).toBe(1)
  expect(writes[0].body).toEqual({plan_version:2});expect(writes[0].key).toBeTruthy()
  await page.locator('[data-input-state]').click()
  await page.locator('[data-open-inputs]').click()
  await page.getByLabel('补充资料',{exact:false}).fill('办公室通勤使用')
  await page.locator('[data-send-inputs]').click()
  await expect.poll(()=>writes.length).toBe(2)
  expect(writes[1].body).toEqual({text:'办公室通勤使用'})
  const configure=page.getByRole('button',{name:'配置服务连接',exact:true}).first()
  await configure.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('服务访问 Key',{exact:true}).fill('TEST_ONLY_never_persist')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('服务访问 Key',{exact:true})).toHaveValue('TEST_ONLY_never_persist')
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  await configure.click()
  await expect(page.getByLabel('服务访问 Key',{exact:true})).toHaveValue('')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
  await page.screenshot({path:resolve('../docs/verification/screenshots/element-plus-2026-10-16-media-controls-'+info.project.name+'.png'),fullPage:true})
  expect(errors).toEqual([])
})
