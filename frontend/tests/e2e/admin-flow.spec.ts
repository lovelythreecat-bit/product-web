import { expect, test } from '@playwright/test'
import { runtime, registerUI } from './workspace-support'

test('TEST_ONLY admin target ledger recovers lost grant response with original intent', async ({page}) => {
  const {meta}=await runtime()
  await registerUI(page,meta.account_prefix+'target_')
  const target=await page.evaluate(async()=>{const p='/src/api/auth.ts';return (await import(p)).getProfile()})
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await page.getByLabel('账号',{exact:true}).fill(meta.account_prefix+'admin')
  await page.getByLabel('密码',{exact:true}).fill('TEST_ONLY_browser_password')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByRole('link',{name:'管理后台',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'管理后台',exact:true}).click()
  await expect(page.getByRole('heading',{name:'用户与积分',exact:true})).toBeVisible()
  const before=await page.evaluate(async id=>{const a='/src/api/admin.ts',b='/src/api/account.ts';return {target:await(await import(a)).userAccount(id),own:await(await import(b)).getAccount()}},target.user_id)
  await page.getByRole('button',{name:'查看账户 '+target.account,exact:true}).click()
  await expect(page.getByTestId('admin-target-available')).toHaveText(String(before.target.available))
  await page.getByRole('button',{name:'发放积分',exact:true}).click()
  await page.getByLabel('发放积分数',{exact:true}).fill('17')
  await page.getByLabel('发放原因',{exact:true}).fill('TEST_ONLY T19b original grant')
  await page.getByRole('button',{name:'确认发放信息',exact:true}).click()
  const confirmation=page.getByRole('dialog',{name:'确认积分发放',exact:true})
  await expect(confirmation.getByRole('button',{name:'取消',exact:true})).toBeFocused()
  let originalBody=''
  await page.route('**/api/v1/admin/credit-grants',async route=>{
    originalBody=route.request().postData()!
    const response=await route.fetch()
    expect(response.status()).toBe(200)
    await route.abort('failed')
  },{times:1})
  await confirmation.getByRole('button',{name:'确认发放',exact:true}).click()
  await expect(confirmation.getByRole('alert')).toContainText('网络连接失败')
  const stored=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('admin-credit-intent:')).map(k=>JSON.parse(localStorage.getItem(k)!)))
  expect(stored).toHaveLength(1)
  expect(stored[0].body).toBe(originalBody)
  await page.reload()
  await expect(page.getByRole('heading',{name:'有一笔发放待核对'})).toBeVisible()
  const retry=page.waitForRequest(r=>r.url().endsWith('/api/v1/admin/credit-grants')&&r.method()==='POST')
  await page.getByRole('button',{name:'同键重试发放',exact:true}).click()
  expect((await retry).postData()).toBe(originalBody)
  await expect(page.getByText('发放已确认：17 积分',{exact:false})).toBeVisible()
  const after=await page.evaluate(async id=>{const a='/src/api/admin.ts',b='/src/api/account.ts';const api=await import(a);return {target:await api.userAccount(id),own:await(await import(b)).getAccount(),ledger:await api.userLedger(id)}},target.user_id)
  expect(after.target.available).toBe(before.target.available+17)
  expect(after.own).toEqual(before.own)
  expect(after.ledger.items.filter((x:{reason:string})=>x.reason==='TEST_ONLY T19b original grant')).toHaveLength(1)
  expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('admin-credit-intent:')))).toHaveLength(0)
  await page.getByRole('link',{name:'任务与用量',exact:true}).click()
  await expect(page.getByText('不可获得（unavailable）',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('账号',{exact:true}).fill(target.account)
  await page.getByLabel('密码',{exact:true}).fill('TEST_ONLY_browser_password')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page).toHaveURL(/\/workspace$/)
  await page.goto('/admin/users')
  await expect(page).toHaveURL(/\/workspace$/)
  await expect(page.getByRole('link',{name:'管理后台',exact:true})).toHaveCount(0)
})
