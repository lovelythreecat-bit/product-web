test('uncertain_submit_replays_original_after_reload and all Agents release once on signed failure', async ({ page }, info) => {
  test.setTimeout(120000)
  const { meta, command } = await runtime()
  await registerUI(page, meta.account_prefix + 'uncertain_')
  const requests: { body: string; key: string }[] = [], evidence: unknown[] = []
  await page.route('**/api/v1/tasks', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    requests.push({ body: route.request().postData()!, key: route.request().headers()['idempotency-key'] })
    if (requests.length === 1) { expect((await route.fetch()).ok()).toBe(true); await route.abort('failed') }
    else await route.continue()
  })
  for (const [kind, credits] of [['copy', 8], ['image', 20], ['video', 60]] as const) {
    await newConversationUI(page)
    await page.getByLabel('选择 Agent').selectOption(meta.agents[kind])
    await productUI(page)
    if (kind !== 'copy') await uploadUI(page)
    const before = await account(page)
    await (await confirmUI(page, credits)).getByRole('button', { name: '同意并冻结积分' }).click()
    if (kind === 'copy') {
      await expect(page.getByRole('dialog', { name: '确认本次创作' }).getByRole('alert')).toContainText('提交结果尚未确认')
      await page.reload()
      await expect(page.locator('[data-task-id]')).toHaveCount(1)
      await page.getByRole('button', { name: '核对并重试原请求' }).click()
      const dialog = page.getByRole('dialog', { name: '确认本次创作' })
      await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
      await dialog.getByRole('button', { name: '同意并冻结积分' }).click()
      await expect(dialog).not.toBeVisible()
      expect(requests).toHaveLength(2)
      expect(requests[1]).toEqual(requests[0])
    }
    await expect(page.locator('[data-task-id]')).toHaveCount(1)
    const id = (await page.locator('[data-task-id]').getAttribute('data-task-id'))!
    const frozen = await account(page)
    expect(frozen.account.frozen).toBe(credits)
    expect(frozen.ledger.items.filter((x: any) => x.task_id === id && x.kind === 'freeze')).toHaveLength(1)
    await command('/register', { task_id: id, paused: true })
    await command('/drive', { task_id: id })
    const notification = await command('/notify', { task_id: id, failure: true })
    expect(notification.receipts).toEqual(['ACCEPTED', 'DUPLICATE'])
    const failed = await command('/drive', { task_id: id })
    expect(failed.state).toBe('FAILED')
    expect(failed.work_ids).toHaveLength(0)
    expect(failed.calls.submit).toBe(1)
    expect(failed.ledger.filter((x: any) => x.task_id === id && x.kind === 'release')).toHaveLength(1)
    expect(failed.ledger.filter((x: any) => x.task_id === id && x.kind === 'consume')).toHaveLength(0)
    await expect(page.locator('[data-task-id]')).toContainText('已释放', { timeout: 15000 })
    expect((await account(page)).account).toEqual(before.account)
    evidence.push({ kind, credits, id, before, frozen, failed, notification, detail: await taskDetail(page, id) })
  }
  await page.getByRole('link', { name: '我的作品', exact: true }).click()
  await expect(page.locator('[data-work-id]')).toHaveCount(0)
  await writeFile(info.outputPath('uncertain-failure-evidence.json'), JSON.stringify({ requests, evidence }, null, 2))
})

