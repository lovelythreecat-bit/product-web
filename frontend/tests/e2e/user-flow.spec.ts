test('refresh_disconnect_original uses native reset compensation without another POST', async ({ page, context }, info) => {
  const { meta, command } = await runtime()
  await page.addInitScript(() => {
    const Native = window.EventSource
    const records: any[] = []; (window as any).streamEvidence = records
    window.EventSource = class extends Native {
      constructor(url: string | URL, options?: EventSourceInit) { super(url, options); records.push({ action: 'open', url: String(url) }); for (const type of ['task.updated', 'reset', 'transient_fragment']) this.addEventListener(type, event => { const e = event as MessageEvent; records.push({ action: type, id: e.lastEventId, data: JSON.parse(e.data) }) }) }
      close() { records.push({ action: 'close', url: this.url }); super.close() }
    }
  })
  await registerUI(page, meta.account_prefix + 'stream_')
  await page.getByLabel('选择 Agent').selectOption(meta.agents.copy); await productUI(page)
  let posts = 0; page.on('request', r => { if (new URL(r.url()).pathname === '/api/v1/tasks' && r.method() === 'POST') posts++ })
  await (await confirmUI(page, 8)).getByRole('button', { name: '同意并冻结积分' }).click()
  await expect(page.locator('[data-task-id]')).toHaveCount(1)
  const id = (await page.locator('[data-task-id]').getAttribute('data-task-id'))!
  await command('/register', { task_id: id, paused: true })
  await command('/drive', { task_id: id })
  await expect.poll(() => page.evaluate(() => (window as any).streamEvidence.filter((x: any) => x.action === 'task.updated').length)).toBeGreaterThan(0)
  await context.setOffline(true)
  const complete = await command('/drive', { task_id: id })
  expect(complete.state).toBe('SUCCEEDED')
  const pruned = await command('/prune', { task_id: id })
  await context.setOffline(false)
  await expect(page.locator('[data-task-id]')).toContainText('生成成功', { timeout: 20000 })
  await expect.poll(() => page.evaluate(() => (window as any).streamEvidence.some((x: any) => x.action === 'reset'))).toBe(true)
  await expect.poll(() => page.evaluate(() => {
    const records = (window as any).streamEvidence
    const reset = records.find((x: any) => x.action === 'reset')
    return records.some((x: any) => x.action === 'open' && x.url.includes(encodeURIComponent(reset.id)))
  })).toBe(true)
  const events = await page.evaluate(() => (window as any).streamEvidence)
  const reset = events.find((x: any) => x.action === 'reset')
  expect(events.some((x: any) => x.action === 'open' && x.url.includes(encodeURIComponent(reset.id)))).toBe(true)
  const beforeReload = await taskDetail(page, id)
  await page.reload()
  await expect(page.locator('[data-task-id]')).toHaveAttribute('data-task-id', id)
  expect(await taskDetail(page, id)).toEqual(beforeReload)
  expect(posts).toBe(1)
  const persisted = await command('/inspect', { task_id: id })
  expect(persisted.calls.submit).toBe(1)
  expect(persisted.ledger.filter((x: any) => x.task_id === id && x.kind === 'consume')).toHaveLength(1)
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(k => k.startsWith('creation-drafts-v1:')))).toEqual([])
  await writeFile(info.outputPath('stream-evidence.json'), JSON.stringify({ id, pruned, complete, events, persisted, posts }, null, 2))
})
