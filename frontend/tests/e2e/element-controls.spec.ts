import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'
import { selectOption } from './ui-controls'

test('suggested text can be changed by reopening the list without editing the existing value', async ({ page }) => {
  await page.goto('/tests/fixtures/element-controls.html')
  await page.getByRole('button', { name: '编辑测试资料' }).click()
  const input = page.getByLabel('可自定义要求', { exact: true })
  await input.click()
  await page.getByRole('option', { name: '自然', exact: true }).click()
  await expect(input).toHaveValue('自然')
  await input.click()
  await expect(page.getByRole('option')).toHaveText(['自然', '专业', '亲切'])
  await page.getByRole('option', { name: '专业', exact: true }).click()
  await expect(input).toHaveValue('专业')
  await page.getByRole('heading', { name: '测试资料', exact: true }).click()
  await input.focus()
  await expect(page.getByRole('option')).toHaveText(['自然', '专业', '亲切'])
  await input.fill('亲')
  await expect(page.getByRole('option')).toHaveText(['亲切'])
  await input.fill('直接坦诚，保留商品事实')
  await expect(page.getByRole('option')).toHaveCount(0)
  await input.click()
  await expect(page.getByRole('option')).toHaveText(['自然', '专业', '亲切'])
  await expect(input).toHaveValue('直接坦诚，保留商品事实')
  await input.press('Escape')
  await expect(page.getByRole('option')).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: '测试资料' })).toBeVisible()
})

test('native validation, typed values, fieldset freeze and nested keyboard dismissal survive the migration', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/tests/fixtures/element-controls.html')
  const trigger = page.getByRole('button', { name: '编辑测试资料' })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '测试资料' })
  await expect(page.getByLabel('商品名称', { exact: true })).toBeFocused()
  await page.getByRole('button', { name: '保存测试资料' }).click()
  await expect(drawer).toBeVisible()
  await expect(page.locator('[data-saved]')).toHaveText('尚未保存')
  await page.getByLabel('商品名称', { exact: true }).fill('测试马克杯')
  await page.getByLabel('测试数量').fill('2')
  const status = page.getByRole('combobox', { name: '配置状态', exact: true })
  await page.getByRole('button', { name: '模拟提交冻结' }).click()
  await expect(status).toBeDisabled()
  await expect(page.getByLabel('商品名称', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '解除冻结' }).click()
  await expect(status).toBeEnabled()
  await selectOption(status, 'false')
  await status.focus(); await status.press('ArrowDown')
  await expect(status).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(status).toHaveAttribute('aria-expanded', 'false')
  await expect(drawer).toBeVisible()
  const custom = page.getByLabel('可自定义要求', { exact: true })
  await custom.fill('直接坦诚，保留商品事实')
  await page.getByRole('heading', { name: '测试资料', exact: true }).click()
  await page.screenshot({ path: resolve('../docs/verification/screenshots/element-plus-controls-' + info.project.name + '.png'), fullPage: true })
  await page.getByRole('button', { name: '保存测试资料' }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.locator('[data-saved]')).toHaveText('{"name":"测试马克杯","amount":2,"enabled":false,"custom":"直接坦诚，保留商品事实"}')
  await expect(trigger).toBeFocused()
  const charge = page.getByRole('button', { name: '测试费用确认', exact: true })
  await charge.click()
  const dialog = page.getByRole('dialog', { name: '测试费用确认' })
  await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).not.toBeVisible(); await expect(charge).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  expect(errors).toEqual([])
})
