import { expect, test } from '@playwright/test'

test('dynamic V2 keeps public navigation, themed demos and accessible controls', async ({ page }) => {
  await page.route('**/api/v1/site/content', route => route.fulfill({ json: { content: null } }))
  await page.route('**/api/v1/site/cases', route => route.fulfill({ json: [] }))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('一站式电商内容工具，小白十分钟高效出片')
  await expect(page.locator('.orbit-card')).toHaveCount(3)
  await expect(page.locator('.lingling-invite img')).toBeVisible()
  await expect(page.locator('.review-tools, dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.locator('[data-select-product="1"]').click()
  await expect(page.locator('[data-product="1"]')).toHaveAttribute('data-slot', 'active')
  await expect(page.locator('.gallery-auto')).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.orbit-gallery').press('ArrowRight')
  await expect(page.locator('[data-product="2"]')).toHaveAttribute('data-slot', 'active')
  await page.locator('.hero-process-link').click()
  await expect(page).toHaveURL(/#creation$/)
  await page.locator('[data-step="2"]').click()
  await expect(page.locator('.scene-video')).toHaveAttribute('aria-hidden', 'false')
  await expect(page.locator('.scene-input')).toHaveAttribute('inert', '')
  const before = await page.locator('.story-screen').evaluate(el => getComputedStyle(el).backgroundColor)
  await page.locator('.theme-toggle').click()
  await expect.poll(() => page.locator('.story-screen').evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(before)
  await page.locator('.nav a[href="/register"]').click()
  await expect(page).toHaveURL(/\/register$/)
  await page.goto('/')
  await expect(page.locator('.hero-message h1')).toBeVisible()
  await page.locator('.hero-primary a[href="/register"]').click()
  await expect(page).toHaveURL(/\/register$/)
})
