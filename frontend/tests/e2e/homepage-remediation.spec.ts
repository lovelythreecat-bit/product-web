import { expect, test } from '@playwright/test'

test('lightfield homepage keeps public navigation, themed demos and accessible controls', async ({ page }) => {
  await page.route('**/api/v1/site/content', route => route.fulfill({ json: { content: null } }))
  await page.route('**/api/v1/site/cases', route => route.fulfill({ json: [] }))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('一站式电商内容工具，小白十分钟高效出片')
  await expect(page.locator('.product-plane')).toHaveCount(3)
  await expect(page.locator('.lingling-link img')).toBeVisible()
  await expect(page.locator('.review-tools, dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.locator('[data-select="1"]').click()
  await expect(page.locator('[data-product="1"]')).toHaveAttribute('data-slot', '0')
  await page.locator('.orbit-system').press('ArrowRight')
  await expect(page.locator('[data-product="2"]')).toHaveAttribute('data-slot', '0')
  await page.locator('.nav a[href="#creation"]').click()
  await expect(page).toHaveURL(/#creation$/)
  await page.locator('[data-step="2"]').click()
  await expect(page.locator('.scene-two')).toHaveAttribute('aria-hidden', 'false')
  await expect(page.locator('.scene-zero')).toHaveAttribute('inert', '')
  const before = await page.locator('.creation-stage').evaluate(el => getComputedStyle(el).backgroundColor)
  await page.locator('.theme-toggle').click()
  await expect.poll(() => page.locator('.creation-stage').evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(before)
  await page.locator('.nav a[href="/register"]').click()
  await expect(page).toHaveURL(/\/register$/)
  await page.goto('/')
  await expect(page.locator('.hero-head h1')).toBeVisible()
  await page.locator('.hero-intro a[href="/register"]').click()
  await expect(page).toHaveURL(/\/register$/)
})
