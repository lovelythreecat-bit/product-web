import { expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { defineComponent } from 'vue'
import { ApiError } from '../../src/api/client'
const api=vi.hoisted(()=>({listUsers:vi.fn(),registrationConfig:vi.fn(),saveRegistrationConfig:vi.fn()}))
vi.mock('../../src/api/admin',()=>api)
vi.mock('../../src/features/auth/session',()=>({session:{epoch:{value:0},profile:{value:{user_id:'admin'}}},onIdentityChange:()=>()=>{}}))
vi.mock('../../src/features/admin/creditIntent',()=>({restoreGrant:()=>null,rememberGrant:vi.fn(),forgetGrant:vi.fn()}))
import UsersView from '../../src/features/admin/UsersView.vue'

it('explicitly creates the first config with null CAS, retaining drafts and protecting a subsequently known baseline',async()=>{
 api.listUsers.mockResolvedValue({items:[],next_cursor:null})
 api.registrationConfig.mockRejectedValue(new ApiError('配置读取未完成',403,'FEATURE_NOT_ENABLED'))
 api.saveRegistrationConfig.mockRejectedValue(new ApiError('版本冲突',409,'VERSION_CONFLICT'))
 const overlay=defineComponent({props:['open'],template:'<section v-if="open"><slot/><slot name="actions"/></section>'})
 const wrapper=mount(UsersView,{global:{stubs:{AppDrawer:overlay,AppDialog:overlay}}})
 const button=(label:string)=>wrapper.findAll('button').find(b=>b.text()===label)!
 await flushPromises()
 await button('注册赠送配置').trigger('click')
 await flushPromises()
 const form=wrapper.get('#registration-config')
 const fields=form.findAll('input')
 await fields[0].setValue('27')
 await fields[1].setValue('TEST_ONLY_D05')
 await form.get('textarea').setValue('首份配置原因')
 expect(button('保存配置').attributes('disabled')).toBeDefined()
 expect(api.saveRegistrationConfig).not.toHaveBeenCalled()
 await button('创建首份配置').trigger('click')
 expect(form.text()).toContain('空版本（首份配置）')
 expect(form.text()).toContain('配置读取未完成')
 expect(button('保存配置').attributes('disabled')).toBeUndefined()
 await form.trigger('submit')
 await flushPromises()
 expect(api.saveRegistrationConfig).toHaveBeenLastCalledWith({expected_version:null,amount:27,policy_version:'TEST_ONLY_D05',reason:'首份配置原因'})
 expect(form.text()).toContain('草稿已保留')
 expect((fields[0].element as HTMLInputElement).value).toBe('27')
 const known={version:'00000000-0000-4000-8000-000000000001',amount:9,policy_version:'OTHER_D05',reason:'existing',mode:'mock',test_only:true,created_at:'2026-10-12T00:00:00Z'}
 api.registrationConfig.mockResolvedValue(known)
 await button('查询当前版本（保留草稿）').trigger('click')
 await flushPromises()
 expect((fields[0].element as HTMLInputElement).value).toBe('27')
 expect((fields[1].element as HTMLInputElement).value).toBe('TEST_ONLY_D05')
 expect(button('保存配置').attributes('disabled')).toBeDefined()
 expect(button('创建首份配置')).toBeUndefined()
 await form.trigger('submit')
 expect(api.saveRegistrationConfig).toHaveBeenCalledTimes(1)
 await button('已核对，采用当前版本继续编辑').trigger('click')
 api.registrationConfig.mockRejectedValue(new ApiError('读取暂时失败',503))
 await button('查询当前版本（保留草稿）').trigger('click')
 await flushPromises()
 expect(form.text()).toContain(known.version)
 api.saveRegistrationConfig.mockResolvedValue({...known,amount:27})
 await form.trigger('submit')
 await flushPromises()
 expect(api.saveRegistrationConfig).toHaveBeenLastCalledWith({expected_version:known.version,amount:27,policy_version:'TEST_ONLY_D05',reason:'首份配置原因'})
 expect(wrapper.find('#registration-config').exists()).toBe(false)
 wrapper.unmount()
})
