it('a late previous avatar cannot overwrite the current avatar in the same identity', async () => {
  const { default: UserAvatar } = await import('../../src/components/UserAvatar.vue')
  const create = vi.fn(() => 'blob:current-avatar'), revoke = vi.fn()
  vi.stubGlobal('URL', { createObjectURL: create, revokeObjectURL: revoke })
  let resolveOld!: (blob: Blob) => void
  files.getFileContentBlob.mockReturnValueOnce(new Promise<Blob>(r => { resolveOld = r })).mockResolvedValueOnce(new Blob(['new'], { type: 'image/png' }))
  const wrapper = track(mount(UserAvatar, { props: { name: '小陶', avatar: { file_id: 'old', version: 'v1' } } }))
  await wrapper.setProps({ avatar: { file_id: 'new', version: 'v2' } }); await flushPromises()
  const oldSignal = files.getFileContentBlob.mock.calls[0][1] as AbortSignal
  expect(oldSignal.aborted).toBe(true); expect(wrapper.get('img').attributes('src')).toBe('blob:current-avatar')
  resolveOld(new Blob(['old'], { type: 'image/png' })); await flushPromises()
  expect(create).toHaveBeenCalledTimes(1); expect(wrapper.get('img').attributes('src')).toBe('blob:current-avatar')
})
