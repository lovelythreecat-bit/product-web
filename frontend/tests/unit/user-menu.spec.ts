it('avatar loads only the authenticated platform file blob and revokes it on replacement and unmount', async () => {
  const { default: UserAvatar } = await import('../../src/components/UserAvatar.vue')
  const create = vi.fn().mockReturnValueOnce('blob:avatar-one').mockReturnValueOnce('blob:avatar-two'), revoke = vi.fn()
  vi.stubGlobal('URL', { createObjectURL: create, revokeObjectURL: revoke })
  files.getFileContentBlob.mockResolvedValue(new Blob(['image'], { type: 'image/png' }))
  const wrapper = track(mount(UserAvatar, { props: { name: '小陶', avatar: { file_id: 'file-one', version: 'v1' } } }))
  await flushPromises(); expect(wrapper.get('img').attributes('src')).toBe('blob:avatar-one')
  expect(files.getFileContentBlob).toHaveBeenCalledWith('file-one', expect.any(AbortSignal))
  await wrapper.setProps({ avatar: { file_id: 'file-two', version: 'v2' } }); await flushPromises()
  expect(wrapper.get('img').attributes('src')).toBe('blob:avatar-two'); expect(revoke).toHaveBeenCalledWith('blob:avatar-one')
  wrapper.unmount(); expect(revoke).toHaveBeenCalledWith('blob:avatar-two')
})
