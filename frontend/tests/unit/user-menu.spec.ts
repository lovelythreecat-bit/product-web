it('account menu supports keyboard traversal, Escape focus return and outside dismissal', async () => {
  const { default: UserMenu } = await import('../../src/components/UserMenu.vue')
  const wrapper = track(mount(UserMenu, { global, attachTo: document.body }))
  const trigger = wrapper.get('button[aria-haspopup="menu"]')
  await trigger.trigger('keydown', { key: 'ArrowDown' }); await flushPromises()
  const items = wrapper.findAll('[role="menuitem"]')
  expect(items.map(item => item.text())).toEqual(['进入工作台', '个人中心', '退出登录'])
  expect(items[0].attributes('target')).toBe('_blank')
  expect(document.activeElement).toBe(items[0].element)
  await items[0].trigger('keydown', { key: 'ArrowDown' }); expect(document.activeElement).toBe(items[1].element)
  await items[1].trigger('keydown', { key: 'End' }); expect(document.activeElement).toBe(items[2].element)
  await items[2].trigger('keydown', { key: 'Escape' }); await flushPromises()
  expect(wrapper.find('[role="menu"]').exists()).toBe(false); expect(document.activeElement).toBe(trigger.element)
  await trigger.trigger('click'); document.body.click(); await flushPromises()
  expect(wrapper.find('[role="menu"]').exists()).toBe(false)
})
