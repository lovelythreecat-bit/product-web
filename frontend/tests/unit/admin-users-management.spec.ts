it('retains actor-specific financial intent through the real 401, logout and account-switch listeners',async()=>{
 vi.resetModules()
 vi.doUnmock('../../src/features/auth/session')
 vi.doUnmock('../../src/api/adminUsers')
 const auth=await import('../../src/features/auth/session')
 const actual=await import('../../src/api/adminUsers')
 const client=await import('../../src/api/client')
 const events:string[]=[]
 const unsubscribe=auth.onIdentityChange(change=>events.push(change.reason))
 const fetcher=vi.fn()
 vi.stubGlobal('fetch',fetcher)
 const signIn=async(userId:string)=>{
  fetcher.mockResolvedValueOnce(new Response(JSON.stringify({profile:{user_id:userId,role:'admin'},replayed:false}),{status:200,headers:{'Content-Type':'application/json'}}))
  expect(await auth.session.authenticate({account:'administrator',password:'test-password'})).toBe(true)
 }
 try{
  await signIn('actor-a')
  const first=actual.rememberAdjustment('actor-a','target',12,'原调整')
  fetcher.mockResolvedValueOnce(new Response(JSON.stringify({error:{code:'UNAUTHENTICATED',message:'请重新登录'}}),{status:401,headers:{'Content-Type':'application/json'}}))
  await expect(client.request('/api/v1/me')).rejects.toMatchObject({status:401})
  expect(events).toContain('unauthorized')
  expect(auth.session.profile.value).toBeNull()
  await signIn('actor-a')
  expect(actual.restoreAdjustment(auth.session.profile.value!.user_id)).toEqual(first)
  fetcher.mockResolvedValueOnce(new Response(null,{status:204}))
  await auth.session.logout()
  expect(events).toContain('logout')
  await signIn('actor-b')
  expect(actual.restoreAdjustment(auth.session.profile.value!.user_id)).toBeNull()
  const second=actual.rememberAdjustment('actor-b','another-target',3,'另一管理员调整')
  await signIn('actor-a')
  expect(actual.restoreAdjustment(auth.session.profile.value!.user_id)).toEqual(first)
  expect(actual.restoreAdjustment('actor-b')).toEqual(second)
  expect(()=>actual.rememberAdjustment('actor-a','target',12,'重复')).toThrow('待确认')
 }finally{unsubscribe();vi.unstubAllGlobals()}
})
